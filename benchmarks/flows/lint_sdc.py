#!/usr/bin/env python3
"""Lint and optionally repair simple AES SDC files for P0 signoff evidence."""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path


def effective_lines(path: Path) -> list[str]:
    lines: list[str] = []
    if not path.is_file():
        return lines
    for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
        stripped = line.strip()
        if not stripped or stripped.startswith("#"):
            continue
        lines.append(stripped)
    return lines


def lint_sdc(path: Path) -> dict:
    return lint_sdc_with_policy(path, require_output_load=False)


def lint_sdc_with_policy(path: Path, *, require_output_load: bool) -> dict:
    lines = effective_lines(path)
    text = "\n".join(lines)
    checks = {
        "has_clock": bool(re.search(r"\bcreate_(generated_)?clock\b", text)),
        "has_input_delay": "set_input_delay" in text,
        "has_output_delay": "set_output_delay" in text,
        "has_input_slew_or_driver": ("set_input_transition" in text) or ("set_driving_cell" in text),
        "has_output_load": "set_load" in text,
        "has_clock_uncertainty": "set_clock_uncertainty" in text,
    }
    required = [
        "has_clock",
        "has_input_delay",
        "has_output_delay",
        "has_input_slew_or_driver",
        "has_clock_uncertainty",
    ]
    if require_output_load:
        required.append("has_output_load")
    failures = [name for name in required if not checks[name]]
    warnings = []
    if not checks["has_output_load"] and not require_output_load:
        warnings.append(
            "has_output_load: set_load omitted by default because docs/ai/27-iSTA.md records set_load core-dump risk"
        )
    return {
        "schema": "c-sdc-lint/v1",
        "sdc": str(path),
        "exists": path.is_file(),
        "non_comment_lines": len(lines),
        "required_checks": required,
        "checks": checks,
        "failures": failures,
        "warnings": warnings,
        "pass": path.is_file() and len(lines) > 0 and not failures,
    }


def repaired_sdc(
    *,
    clock_period: float,
    clock_name: str,
    clock_port: str,
    input_delay_ratio: float,
    output_delay_ratio: float,
    input_transition: float,
    clock_uncertainty_ratio: float,
    output_load: float | None,
) -> str:
    lines = [
        "# Auto-generated by benchmarks/flows/lint_sdc.py --repair",
        "set clk_name  " + clock_name,
        "set clk_port_name " + clock_port,
        f"set clk_period {clock_period:g}",
        f"set clk_io_pct {input_delay_ratio:g}",
        f"set clk_out_pct {output_delay_ratio:g}",
        f"set clk_uncertainty_pct {clock_uncertainty_ratio:g}",
        f"set input_transition_ns {input_transition:g}",
        "",
        "set clk_port [get_ports $clk_port_name]",
        "set data_inputs [all_inputs]",
        "",
        "create_clock -name $clk_name -period $clk_period $clk_port",
        "set_clock_uncertainty [expr $clk_period * $clk_uncertainty_pct] [get_clocks $clk_name]",
        "set_input_delay  [expr $clk_period * $clk_io_pct] -clock $clk_name $data_inputs",
        "set_output_delay [expr $clk_period * $clk_out_pct] -clock $clk_name [all_outputs]",
        "set_input_transition $input_transition_ns $data_inputs",
    ]
    if output_load is not None:
        lines.append(f"set_load {output_load:g} [all_outputs]")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--sdc", type=Path, required=True)
    parser.add_argument("--output-json", type=Path, default=None)
    parser.add_argument("--repair", action="store_true")
    parser.add_argument("--clock-period", type=float, default=2.5)
    parser.add_argument("--clock-name", default="core_clock")
    parser.add_argument("--clock-port", default="clk")
    parser.add_argument("--input-delay-ratio", type=float, default=0.2)
    parser.add_argument("--output-delay-ratio", type=float, default=0.2)
    parser.add_argument("--input-transition", type=float, default=0.05)
    parser.add_argument("--clock-uncertainty-ratio", type=float, default=0.05)
    parser.add_argument("--output-load", type=float, default=None)
    parser.add_argument(
        "--require-output-load",
        action="store_true",
        help="Treat missing set_load as a hard lint failure. Default is warning-only due to known iSTA risk.",
    )
    args = parser.parse_args()

    if args.repair:
        args.sdc.parent.mkdir(parents=True, exist_ok=True)
        args.sdc.write_text(
            repaired_sdc(
                clock_period=args.clock_period,
                clock_name=args.clock_name,
                clock_port=args.clock_port,
                input_delay_ratio=args.input_delay_ratio,
                output_delay_ratio=args.output_delay_ratio,
                input_transition=args.input_transition,
                clock_uncertainty_ratio=args.clock_uncertainty_ratio,
                output_load=args.output_load,
            ),
            encoding="ascii",
        )

    result = lint_sdc_with_policy(args.sdc, require_output_load=args.require_output_load)
    if args.output_json:
        args.output_json.parent.mkdir(parents=True, exist_ok=True)
        args.output_json.write_text(json.dumps(result, indent=2) + "\n", encoding="utf-8")
    else:
        print(json.dumps(result, indent=2))
    return 0 if result["pass"] else 1


if __name__ == "__main__":
    raise SystemExit(main())
